"""Run the webhook intake and the cancellation deliveries.

Chapter 06 runs the copy of this file under work/app.
Do not edit this file, in the packet or under work/app.
The two copies have to stay the same bytes.

The command reads the pack you pass with --pack. It writes a
trace with --out and a database with --db. It prints nothing
of its own. The prompt returns when the trace is written.
The journey check does not read the trace. It loads intake,
cancel, and mart and runs them again.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import cancel
import intake
import mart
import session


def _events(path: Path) -> list[dict]:
    """Load every non-empty line of a JSONL file as one event.

    path is the cancellation file in the pack. Blank lines are
    skipped. The order of the file is the order of the rows.
    """
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main(argv: list[str] | None = None) -> None:
    """Read the pack, run intake and each cancellation, and write the trace.

    --pack is the release folder. The registry, the webhook, the
    cancellation file, the SMS faults, and the wait-time extract
    are read from that folder. They are not copied into work/.

    The trace keeps the intake mode, the referral id, and the
    ignored keys. It does not keep the webhook body. Each
    cancellation row is the dict apply returned. The mart section
    is whatever mart.read returns for the extract.
    """
    # Read the pack, the database path, and where the trace should be written.
    parser = argparse.ArgumentParser(description="Run wf-session-cancelled on the release pack.")
    parser.add_argument("--pack", required=True)
    parser.add_argument("--db", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    pack = Path(args.pack)
    # The registry, the webhook, and the SMS faults stay in the pack. They are not copied here.
    registry_text = (pack / "registry" / "topics.md").read_text(encoding="utf-8")
    body = json.loads((pack / "webhooks" / "referral.submitted.json").read_text(encoding="utf-8"))
    faults = json.loads((pack / "channels" / "sms-faults.json").read_text(encoding="utf-8"))
    # Accept the webhook, then apply each cancellation in file order.
    accepted = intake.accept(body, registry_text)
    db = session.connect(Path(args.db))
    rows = [cancel.apply(db, event, faults) for event in _events(pack / "events" / "session.cancelled.jsonl")]
    # Keep the intake summary, each cancellation row, and the mart read. Do not keep the webhook body.
    report = {
        "intake": {
            "mode": accepted.get("mode"),
            "referral_id": accepted.get("referral_id"),
            "ignored": accepted.get("ignored", []),
        },
        "cancellations": rows,
        "mart": mart.read((pack / "mart" / "waitlist.csv").read_text(encoding="utf-8")),
    }
    destination = Path(args.out)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8", newline="\n")
    db.close()


if __name__ == "__main__":
    main(sys.argv[1:])
