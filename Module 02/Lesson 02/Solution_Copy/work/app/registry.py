"""Read required fields from the schema registry.

Chapter 06 calls keep from the intake copy under work/app.
Do not edit this file, in the packet or under work/app.
The two copies have to stay the same bytes.

The registry is a markdown table. One row is a topic. The fourth
cell of that row is the comma-separated list of fields a consumer
may store. A key that is not in that list is ignored.
"""

from __future__ import annotations


def required(text: str, topic: str) -> set[str]:
    """Return the field names the registry lists for topic.

    text is the whole registry page. Lines that are not table rows
    are skipped. A row matches when the first cell equals topic.
    The fourth cell is split on commas. An unknown topic returns
    an empty set, which would ignore every key.
    """
    for line in text.splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if cells and cells[0] == topic and len(cells) >= 4:
            return {part.strip() for part in cells[3].split(",") if part.strip()}
    return set()


def keep(body: dict, text: str, topic: str) -> tuple[dict, list[str]]:
    """Split body into fields the registry lists and the rest.

    allowed comes from required. ignored is every key on body that
    is not in that set, sorted so the trace is stable. kept copies
    only the allowed keys that the body actually has. The caller
    decides what to do with each side. This function does not
    reject the event.
    """
    allowed = required(text, topic)
    ignored = sorted(key for key in body if key not in allowed)
    kept = {key: body[key] for key in allowed if key in body}
    return kept, ignored
