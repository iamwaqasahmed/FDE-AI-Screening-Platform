"""Send one SMS. A rejected receipt does not count as sent.

Chapter 06 calls send from the cancellation copy under work/app.
Do not edit this file, in the packet or under work/app.
The two copies have to stay the same bytes.

faults maps a booking id to the word reject when that receipt
fails. Any other booking id is accepted. The body names the
booking. It does not carry a national id.
"""

from __future__ import annotations


def send(booking_id: str, faults: dict) -> dict:
    """Return whether this booking id was accepted.

    A fault value of reject returns ok false and an empty body.
    Every other booking id returns ok true. The body is one
    sentence that names the booking id. Chapter 07 writes the
    patient SMS from that sentence, without a national id.
    """
    if faults.get(str(booking_id)) == "reject":
        return {"ok": False, "body": ""}
    return {"ok": True, "body": f"Your booking {booking_id} has a new time."}
