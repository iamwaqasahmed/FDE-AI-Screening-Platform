"""Create the Week 4 Day 5 workspace.

Chapter 01 runs this file with no extra word. That copies the shell,
the shell tests, the workflow, the blank pages, and the interview
folder into work/.

Run the file from a terminal opened in the course folder. The path
below is enough. You do not need to change directory first.

A second run puts the starter app back, including the eight shell
modules, and it replaces sprint.md, architecture-deploy.md,
operations.md, readout.md, retro.md, knowledge.md, and
rcp/proposal.md with the blanks. It also puts the blank notes back.
The shell tests are copied again. The question files are copied again
and are not replaced. The workflow is copied again and is not
replaced. Run it again only when a failure row says so. Then repeat
the paste steps in chapters 05, 06, 07, 08, and 09.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

# This file's folder is the student copy. Paths below are built from
# here so the script still works when the terminal starts in the course folder.
HERE = Path(__file__).resolve().parent

# The starter shell. Chapter 01 copies it. Later chapters replace
# every module in the work copy. The packet copy stays the trap.
APP = HERE / "packet" / "app"

# The shell tests. Chapter 01 copies them. Later chapters replace the
# work copies. The packet copies stay the shell tests.
TESTS = HERE / "packet" / "tests"

# The blank pages. Later chapters fill the copies, not these originals.
TEMPLATES = HERE / "packet" / "templates"
PAGES = (
    "sprint.md",
    "architecture-deploy.md",
    "operations.md",
    "readout.md",
    "retro.md",
    "knowledge.md",
)

# The questions are copied and not replaced. The notes start blank.
INTERVIEWS = HERE / "packet" / "interviews"

# The workflow. Chapter 01 copies it. This day does not replace it.
PACKET = HERE / "packet"

# The folder the day's checks read.
WORK = HERE / "work"


def _packet_ready() -> bool:
    """True when the drawer this script copies is still beside it.

    The app, the tests, both interview files, the workflow, and every
    blank page have to be present. A missing piece means this file was
    moved, or the packet folder was edited. Copying a partial drawer
    would build a work folder the later chapters cannot finish.
    """
    return (
        APP.is_dir()
        and TESTS.is_dir()
        and INTERVIEWS.is_dir()
        and (INTERVIEWS / "access-mgr.questions.txt").is_file()
        and (INTERVIEWS / "access-mgr.notes.md").is_file()
        and (INTERVIEWS / "ea.questions.txt").is_file()
        and (INTERVIEWS / "ea.notes.md").is_file()
        and (PACKET / ".github" / "workflows" / "ci.yml").is_file()
        and (TEMPLATES / "proposal.md").is_file()
        and all((TEMPLATES / name).is_file() for name in PAGES)
    )


def _copy_tree() -> None:
    """Copy the shell, the tests, the workflow, the blanks, and the interviews.

    An existing work/app and work/tests are removed first so a
    replaced file does not survive a second run. The release drawer
    is not copied.
    """
    for source, name in ((APP, "app"), (TESTS, "tests"), (INTERVIEWS, "interviews")):
        destination = WORK / name
        if destination.exists():
            # A second run must not leave a replaced file mixed with the starter.
            shutil.rmtree(destination)
        # Bytecode is skipped so a local run is not copied in as source.
        shutil.copytree(
            source,
            destination,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
        )
    # The workflow is copied once. No later chapter replaces it.
    workflow = WORK / ".github" / "workflows"
    workflow.mkdir(parents=True, exist_ok=True)
    shutil.copy(PACKET / ".github" / "workflows" / "ci.yml", workflow / "ci.yml")
    # Blank pages land in work/. Later chapters fill those copies, not the packet.
    for name in PAGES:
        shutil.copy(TEMPLATES / name, WORK / name)
    # The proposal blank lives under rcp/, not beside the other pages.
    proposal = WORK / "rcp"
    proposal.mkdir(parents=True, exist_ok=True)
    shutil.copy(TEMPLATES / "proposal.md", proposal / "proposal.md")
    # Keep generated bytecode out of the work folder a student commits.
    (WORK / ".gitignore").write_text(
        "__pycache__/\n*.pyc\n",
        encoding="utf-8",
        newline="\n",
    )


def main() -> None:
    """Copy the workspace. This file takes no extra word.

    Chapter 01 runs it from a terminal opened in the course folder.
    The prints that follow are the list of files later chapters replace.
    """
    # A moved script would copy the wrong drawer, or none.
    if not _packet_ready():
        raise SystemExit("This file must stay next to the packet folder. Do not move it.")
    # An extra word is not a flag. The only form is the file name alone.
    if len(sys.argv) > 1:
        raise SystemExit("Use: python prepare_work.py")
    # work/ may already exist. _copy_tree replaces the pieces a second run resets.
    WORK.mkdir(parents=True, exist_ok=True)
    _copy_tree()
    print("Created work/ from the packet.")
    print("Leave the copies in packet/ unchanged.")
    print()
    print("Chapter 05 replaces work/sprint.md.")
    print("Chapter 06 replaces work/app/signin.py, work/app/bus.py, work/app/handoff.py, work/app/leave.py, work/app/warehouse.py, and the work copies of test_signin.py, test_bus.py, test_handoff.py, test_leave.py, and test_warehouse.py.")
    print("Chapter 07 replaces work/app/rank.py, work/app/gates.py, work/app/personal.py, and the work copies of test_rank.py, test_gates.py, and test_personal.py.")
    print("Chapter 08 replaces work/architecture-deploy.md, work/operations.md, work/rcp/proposal.md, work/readout.md, work/retro.md, work/interviews/access-mgr.notes.md, and work/interviews/ea.notes.md.")
    print("Chapter 09 replaces work/knowledge.md.")
    print()
    print("The packet tests stay the shell tests.")
    print("The question files are copied and not replaced.")
    print("The workflow is copied and not replaced.")
    print()
    print("A second run of this file puts the blanks, the starter app, and the shell tests back.")


if __name__ == "__main__":
    main()
